"""
Build the Phase 4.2A ML training dataset.

Purpose:
    Convert real SGP4 collision-screening observations into a
    physics-aware augmented dataset.

Important:
    This is an initial risk-classification dataset.
    It does NOT represent measured collision probabilities.

The original observation is preserved as the source.
Synthetic observations are generated by perturbing the
physical quantities around that source.

The source_id field is later used to perform a grouped
train/validation split and prevent data leakage.
"""

from __future__ import annotations

import argparse
import json
import math
import random
from pathlib import Path
from typing import Dict, List, Tuple


# ============================================================
# PATHS
# ============================================================

TRAINING_DIR = Path(__file__).resolve().parent

RAW_DATASET = TRAINING_DIR / "orbital_training_data.jsonl"

BALANCED_DATASET = TRAINING_DIR / "balanced_training_data.jsonl"


# ============================================================
# CONFIGURATION
# ============================================================

RANDOM_SEED = 42

AUGMENTATIONS_PER_SOURCE = 20

DISTANCE_MAX_KM = 100.0
VELOCITY_MAX_KMS = 20.0
TCA_MAX_SECONDS = 10800.0


# ============================================================
# RISK CLASSIFICATION
# ============================================================

def determine_risk_level(
    distance_km: float,
    velocity_kms: float,
    tca_seconds: float,
) -> Tuple[str, int]:
    """
    Physics-inspired screening labels.

    These thresholds are used only to create initial training
    classes from orbital observations.

    They are NOT collision probability thresholds.
    """

    # Critical:
    # Extremely close approach with very little time remaining.
    if distance_km <= 5.0 and tca_seconds <= 600.0:
        return "CRITICAL", 3

    # High:
    # Very close approach with limited time remaining.
    if distance_km <= 15.0 and tca_seconds <= 1800.0:
        return "HIGH", 2

    # Medium:
    # Meaningfully close orbital encounter.
    if distance_km <= 30.0 and tca_seconds <= 5400.0:
        return "MEDIUM", 1

    # Additional medium condition for very high-energy encounters.
    if distance_km <= 50.0 and velocity_kms >= 10.0:
        return "MEDIUM", 1

    return "LOW", 0


# ============================================================
# CLAMP
# ============================================================

def clamp(
    value: float,
    minimum: float,
    maximum: float,
) -> float:

    return max(minimum, min(value, maximum))


# ============================================================
# PHYSICS FEATURES
# ============================================================

def calculate_features(
    distance_km: float,
    velocity_kms: float,
    tca_seconds: float,
) -> Dict[str, float]:
    """
    Recalculate the complete independent feature vector.

    We deliberately do NOT use the original backend risk
    classification here.
    """

    distance_normalized = clamp(
        distance_km / DISTANCE_MAX_KM,
        0.0,
        1.0,
    )

    velocity_normalized = clamp(
        velocity_kms / VELOCITY_MAX_KMS,
        0.0,
        1.0,
    )

    tca_normalized = clamp(
        tca_seconds / TCA_MAX_SECONDS,
        0.0,
        1.0,
    )

    distance_risk = 1.0 - distance_normalized

    velocity_risk = velocity_normalized

    time_risk = 1.0 - tca_normalized

    physics_risk_score = clamp(
        (
            0.50 * distance_risk
            + 0.30 * time_risk
            + 0.20 * velocity_risk
        ),
        0.0,
        1.0,
    )

    return {
        "miss_distance_km": distance_km,
        "relative_velocity_kms": velocity_kms,
        "time_to_tca_seconds": tca_seconds,

        "miss_distance_normalized": distance_normalized,
        "relative_velocity_normalized": velocity_normalized,
        "time_to_tca_normalized": tca_normalized,

        "physics_risk_score": physics_risk_score,

        "distance_risk": distance_risk,
        "velocity_risk": velocity_risk,
        "time_risk": time_risk,
    }


# ============================================================
# PERTURBATION
# ============================================================

def perturb_source(
    distance_km: float,
    velocity_kms: float,
    tca_seconds: float,
    rng: random.Random,
) -> Tuple[float, float, float]:
    """
    Create a physically reasonable nearby orbital scenario.

    Perturbations are intentionally moderate so the generated
    samples remain related to the real observation.
    """

    # Log-normal-like distance variation.
    distance_factor = math.exp(
        rng.gauss(0.0, 0.30)
    )

    # Velocity variation.
    velocity_factor = math.exp(
        rng.gauss(0.0, 0.12)
    )

    # TCA variation.
    tca_factor = math.exp(
        rng.gauss(0.0, 0.35)
    )

    new_distance = distance_km * distance_factor
    new_velocity = velocity_kms * velocity_factor
    new_tca = tca_seconds * tca_factor

    return (
        clamp(new_distance, 0.1, DISTANCE_MAX_KM),
        clamp(new_velocity, 0.01, VELOCITY_MAX_KMS),
        clamp(new_tca, 0.0, TCA_MAX_SECONDS),
    )


# ============================================================
# DETERMINISTIC CLASS GENERATION
# ============================================================

def generate_class_scenarios(
    source_distance: float,
    source_velocity: float,
    source_tca: float,
) -> List[Tuple[float, float, float]]:
    """
    Generate deliberate boundary scenarios around the source.

    This gives the model examples from all meaningful risk
    regions instead of relying exclusively on random noise.
    """

    scenarios = []

    # --------------------------------------------------------
    # LOW
    # --------------------------------------------------------

    scenarios.extend([
        (
            max(60.0, source_distance * 1.5),
            source_velocity,
            min(9000.0, max(6000.0, source_tca * 1.5)),
        ),
        (
            max(40.0, source_distance * 1.3),
            source_velocity,
            min(10800.0, max(5000.0, source_tca * 1.3)),
        ),
    ])

    # --------------------------------------------------------
    # MEDIUM
    # --------------------------------------------------------

    scenarios.extend([
        (
            min(30.0, max(20.0, source_distance)),
            source_velocity,
            min(5400.0, max(2400.0, source_tca)),
        ),
        (
            25.0,
            max(1.0, source_velocity),
            3600.0,
        ),
    ])

    # --------------------------------------------------------
    # HIGH
    # --------------------------------------------------------

    scenarios.extend([
        (
            12.0,
            max(1.0, source_velocity),
            1500.0,
        ),
        (
            8.0,
            max(2.0, source_velocity),
            1200.0,
        ),
    ])

    # --------------------------------------------------------
    # CRITICAL
    # --------------------------------------------------------

    scenarios.extend([
        (
            3.0,
            max(2.0, source_velocity),
            300.0,
        ),
        (
            1.0,
            max(5.0, source_velocity),
            120.0,
        ),
    ])

    return scenarios


# ============================================================
# RECORD CREATION
# ============================================================

def create_record(
    sample_id: str,
    source_id: str,
    distance_km: float,
    velocity_kms: float,
    tca_seconds: float,
    augmentation_type: str,
) -> Dict:

    features = calculate_features(
        distance_km,
        velocity_kms,
        tca_seconds,
    )

    risk_level, risk_class = determine_risk_level(
        distance_km,
        velocity_kms,
        tca_seconds,
    )

    return {
        "sample_id": sample_id,
        "source_id": source_id,

        "features": features,

        "target": {
            "risk_level": risk_level,
            "risk_class": risk_class,
        },

        "metadata": {
            "augmentation_type": augmentation_type,
            "generator": "Phase 4.2A physics-aware dataset builder",
            "synthetic": augmentation_type != "original",
        },
    }


# ============================================================
# BUILD DATASET
# ============================================================

def build_dataset() -> List[Dict]:

    if not RAW_DATASET.exists():
        raise FileNotFoundError(
            f"Raw dataset not found: {RAW_DATASET}"
        )

    rng = random.Random(RANDOM_SEED)

    records = []

    with RAW_DATASET.open(
        "r",
        encoding="utf-8",
    ) as file:

        raw_records = [
            json.loads(line)
            for line in file
            if line.strip()
        ]

    print(
        f"[INFO] Loaded {len(raw_records)} real observations."
    )

    for index, raw in enumerate(
        raw_records,
        start=1,
    ):

        source_id = raw.get(
            "sample_id",
            f"collision_{index:06d}",
        )

        features = raw["features"]

        distance = float(
            features["miss_distance_km"]
        )

        velocity = float(
            features["relative_velocity_kms"]
        )

        tca = float(
            features["time_to_tca_seconds"]
        )

        # ----------------------------------------------------
        # Original observation
        # ----------------------------------------------------

        records.append(
            create_record(
                sample_id=f"{source_id}_original",
                source_id=source_id,
                distance_km=distance,
                velocity_kms=velocity,
                tca_seconds=tca,
                augmentation_type="original",
            )
        )

        # ----------------------------------------------------
        # Random nearby scenarios
        # ----------------------------------------------------

        for variation in range(
            AUGMENTATIONS_PER_SOURCE
        ):

            d, v, t = perturb_source(
                distance,
                velocity,
                tca,
                rng,
            )

            records.append(
                create_record(
                    sample_id=(
                        f"{source_id}_random_{variation + 1:02d}"
                    ),
                    source_id=source_id,
                    distance_km=d,
                    velocity_kms=v,
                    tca_seconds=t,
                    augmentation_type="random",
                )
            )

        # ----------------------------------------------------
        # Deliberate class-boundary scenarios
        # ----------------------------------------------------

        scenarios = generate_class_scenarios(
            distance,
            velocity,
            tca,
        )

        for scenario_index, (
            d,
            v,
            t,
        ) in enumerate(
            scenarios,
            start=1,
        ):

            records.append(
                create_record(
                    sample_id=(
                        f"{source_id}_boundary_{scenario_index:02d}"
                    ),
                    source_id=source_id,
                    distance_km=d,
                    velocity_kms=v,
                    tca_seconds=t,
                    augmentation_type="boundary",
                )
            )

    return records


# ============================================================
# BALANCE DATASET
# ============================================================

def balance_dataset(
    records: List[Dict],
) -> List[Dict]:

    grouped = {
        0: [],
        1: [],
        2: [],
        3: [],
    }

    for record in records:

        risk_class = record["target"]["risk_class"]

        grouped[risk_class].append(record)

    counts = {
        risk_class: len(items)
        for risk_class, items in grouped.items()
    }

    print("\n============================================================")
    print("BEFORE BALANCING")
    print("============================================================")

    names = {
        0: "LOW",
        1: "MEDIUM",
        2: "HIGH",
        3: "CRITICAL",
    }

    for risk_class in range(4):
        print(
            f"{names[risk_class]:<12}: "
            f"{counts[risk_class]}"
        )

    # We don't randomly duplicate minority records.
    # The physics-aware generation above is responsible for
    # creating meaningful minority-class examples.

    non_empty = [
        len(items)
        for items in grouped.values()
        if items
    ]

    if not non_empty:
        raise RuntimeError(
            "No valid training classes were generated."
        )

    target_count = max(non_empty)

    balanced = []

    rng = random.Random(RANDOM_SEED)

    for risk_class in range(4):

        items = grouped[risk_class]

        if not items:
            continue

        if len(items) <= target_count:

            expanded = list(items)

            # If still imbalanced, sample with replacement.
            while len(expanded) < target_count:
                expanded.append(
                    rng.choice(items)
                )

            balanced.extend(expanded)

        else:
            balanced.extend(
                rng.sample(
                    items,
                    target_count,
                )
            )

    rng.shuffle(balanced)

    return balanced


# ============================================================
# WRITE DATASET
# ============================================================

def write_dataset(
    records: List[Dict],
) -> None:

    with BALANCED_DATASET.open(
        "w",
        encoding="utf-8",
    ) as file:

        for record in records:

            file.write(
                json.dumps(
                    record,
                    separators=(",", ":"),
                )
                + "\n"
            )


# ============================================================
# SUMMARY
# ============================================================

def print_summary(
    records: List[Dict],
) -> None:

    counts = {
        "LOW": 0,
        "MEDIUM": 0,
        "HIGH": 0,
        "CRITICAL": 0,
    }

    for record in records:

        level = record["target"]["risk_level"]

        if level in counts:
            counts[level] += 1

    print("\n============================================================")
    print("BALANCED TRAINING DATASET")
    print("============================================================")

    print(f"Total samples : {len(records)}")
    print(f"LOW           : {counts['LOW']}")
    print(f"MEDIUM        : {counts['MEDIUM']}")
    print(f"HIGH          : {counts['HIGH']}")
    print(f"CRITICAL      : {counts['CRITICAL']}")

    print("============================================================")


# ============================================================
# MAIN
# ============================================================

def main() -> None:

    parser = argparse.ArgumentParser(
        description="Build Phase 4.2A training dataset."
    )

    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite existing balanced dataset.",
    )

    args = parser.parse_args()

    if (
        BALANCED_DATASET.exists()
        and not args.overwrite
    ):

        raise FileExistsError(
            f"{BALANCED_DATASET} already exists. "
            "Use --overwrite."
        )

    print(
        "[INFO] Building physics-aware training dataset..."
    )

    records = build_dataset()

    print(
        f"[INFO] Generated {len(records)} candidate samples."
    )

    balanced = balance_dataset(records)

    write_dataset(balanced)

    print(
        f"\n[SUCCESS] Dataset written to:\n"
        f"{BALANCED_DATASET}"
    )

    print_summary(balanced)


if __name__ == "__main__":
    main()